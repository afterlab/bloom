#!/usr/bin/env python3
"""Generates src/document/html_named_references.inc from the HTML Standard's entities.json.

WebVTT cue text consumes HTML character references (the WebVTT cue text tokenizer), so Bloom's
cue markup reads every name the HTML Standard defines. The HTML Standard states the list is static
and will never change; the digest below pins the exact bytes this table was generated from.

    python3 tools/subtitles/generate_html_named_references.py           # write the table
    python3 tools/subtitles/generate_html_named_references.py --check   # verify it is current
"""
import hashlib
import json
import pathlib
import sys
import urllib.request

SOURCE = "https://html.spec.whatwg.org/entities.json"
SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"
OUTPUT = pathlib.Path(__file__).resolve().parents[2] / "src/document/html_named_references.inc"


def fetch():
    with urllib.request.urlopen(SOURCE, timeout=60) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{SOURCE} has SHA-256 {digest}, expected {SHA256}")
    return json.loads(data)


def render(entities):
    rows = []
    for name, entry in entities.items():
        points = entry["codepoints"]
        assert name.startswith("&") and 1 <= len(points) <= 2
        second = points[1] if len(points) == 2 else 0
        rows.append((name[1:], points[0], second))
    rows.sort(key=lambda row: row[0].encode("ascii"))
    lines = [
        "// Generated by tools/subtitles/generate_html_named_references.py from",
        f"// {SOURCE} (SHA-256 {SHA256}); do not edit.",
        "// The HTML Standard's named character references, sorted by name (ASCII byte order).",
        "// A name without a trailing ';' is one of the legacy references HTML also accepts",
        "// without it. The including file defines",
        "//   struct HtmlNamedReference { std::string_view name; char32_t first; char32_t second; };",
        f"inline constexpr std::array<HtmlNamedReference, {len(rows)}> kHtmlNamedReferences{{{{",
    ]
    for name, first, second in rows:
        lines.append(f'    {{"{name}", 0x{first:X}, 0x{second:X}}},')
    lines.append("}};")
    return "\n".join(lines) + "\n"


def main():
    text = render(fetch())
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUTPUT.name} is out of date; run {pathlib.Path(__file__).name}")
        return
    OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
