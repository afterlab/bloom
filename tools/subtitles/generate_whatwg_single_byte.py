#!/usr/bin/env python3
"""Generate src/subtitles/whatwg_single_byte_tables.inc from whatwg/encoding.

Usage:
  python3 tools/subtitles/generate_whatwg_single_byte.py          # write the file
  python3 tools/subtitles/generate_whatwg_single_byte.py --check  # verify checked-in file

The upstream revision is pinned; downloads are verified only by recording their
SHA-256 in the generated file, so any upstream drift shows up as a diff.
"""
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

REVISION = "7d2e3e08e11f57ba1b080390b490d53648c6f69c"
BASE = "https://raw.githubusercontent.com/whatwg/encoding/" + REVISION + "/"
HEADING = "Legacy single-byte encodings"
OUTPUT = Path(__file__).resolve().parents[2] / "src" / "subtitles" / "whatwg_single_byte_tables.inc"


def fetch(name):
    with urllib.request.urlopen(BASE + name, timeout=60) as response:
        return response.read()


def identifier(index_name):
    return "k" + "".join(part[:1].upper() + part[1:] for part in index_name.split("-"))


def parse_index(data):
    table = [0] * 128
    for line in data.decode("utf-8").split("\n"):
        line = line.rstrip("\r")
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        pointer = int(fields[0])
        if not 0 <= pointer < 128 or table[pointer] != 0:
            raise ValueError("unexpected index line: " + line)
        table[pointer] = int(fields[1], 16)
    return table


def generate():
    encodings_bytes = fetch("encodings.json")
    groups = json.loads(encodings_bytes)
    group = [g for g in groups if g["heading"] == HEADING]
    if len(group) != 1:
        raise ValueError("heading not found: " + HEADING)
    encodings = group[0]["encodings"]

    shas = [("encodings.json", hashlib.sha256(encodings_bytes).hexdigest())]
    tables = {}  # index name -> table, in first-use order
    entries = []  # (canonical name, index name, labels)
    for encoding in encodings:
        name = encoding["name"].lower()
        index_name = "iso-8859-8" if name == "iso-8859-8-i" else name
        if index_name not in tables:
            data = fetch("index-" + index_name + ".txt")
            shas.append(("index-" + index_name + ".txt", hashlib.sha256(data).hexdigest()))
            tables[index_name] = parse_index(data)
        entries.append((name, index_name, list(encoding["labels"])))

    out = []
    out.append("// Generated by tools/subtitles/generate_whatwg_single_byte.py from whatwg/encoding at "
               + REVISION + "; do not edit.")
    for file_name, digest in shas:
        out.append("// sha256 " + digest + " " + file_name)
    out.append("//")
    out.append("// The including file defines, before including this fragment:")
    out.append("//   struct WhatwgSingleByteEncoding { std::string_view name; "
               "const std::array<char32_t, 128>* table; };")
    out.append("//   struct WhatwgEncodingLabel { std::string_view label; std::size_t encoding; };")
    out.append("// Each table holds the code point for bytes 0x80..0xFF; 0 marks an error byte.")
    out.append("// Labels are sorted by label (byte order) for binary search; `encoding` indexes")
    out.append("// kWhatwgSingleByteEncodings.")
    out.append("")
    for index_name, table in tables.items():
        out.append("constexpr std::array<char32_t, 128> " + identifier(index_name) + "{{")
        for row in range(0, 128, 8):
            out.append("    " + ", ".join("0x%04X" % v for v in table[row:row + 8]) + ",")
        out.append("}};")
        out.append("")
    out.append("constexpr std::array<WhatwgSingleByteEncoding, %d> kWhatwgSingleByteEncodings{{" % len(entries))
    for name, index_name, _ in entries:
        out.append('    {"%s", &%s},' % (name, identifier(index_name)))
    out.append("}};")
    out.append("")
    labels = sorted((label, i) for i, (_, _, ls) in enumerate(entries) for label in ls)
    if len({label for label, _ in labels}) != len(labels):
        raise ValueError("duplicate label")
    for label, _ in labels:
        if not re.fullmatch(r"[a-z0-9_.:\-]+", label):
            raise ValueError("unexpected label: " + label)
    out.append("constexpr std::array<WhatwgEncodingLabel, %d> kWhatwgSingleByteLabels{{" % len(labels))
    for label, i in labels:
        out.append('    {"%s", %d},' % (label, i))
    out.append("}};")
    return "\n".join(out) + "\n"


def main(argv):
    check = "--check" in argv
    text = generate()
    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
        if current != text:
            sys.stderr.write(str(OUTPUT.name) + " is out of date; rerun without --check\n")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
